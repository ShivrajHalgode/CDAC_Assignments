public class DataTypes {
    public static void main(String[] args) {
        int a = 10;
        float b = 5.5f;
        double c = 10.99;
        char d = 'A';
        boolean e = true;
        byte f = 100;
        short g = 2000;
        long h = 100000L;

        System.out.println("Int:"+a + " " +"Float:"+ b + " " +"Double:"+ c + " " + "Char:"+ d + " " +"Boolean:"+ e + " " +"Byte:"+ f + " " +"Short:"+ g + " " +"Long:"+ h);
    }
}